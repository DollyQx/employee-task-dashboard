const LOCAL_STORAGE_KEY = 'bpd_manufacturing_taskflow_data_v1';

export function getStoredManufacturingData() {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed && Array.isArray(parsed.tasks) && parsed.tasks.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.warn('Could not read stored manufacturing data:', err);
  }
  return {
    organization: DEMO_ORGANIZATION,
    users: DEMO_USERS,
    departments: DEMO_DEPARTMENTS,
    projects: DEMO_PROJECTS,
    clients: DEMO_CLIENTS,
    tasks: DEMO_TASKS,
    notifications: DEMO_NOTIFICATIONS,
    auditLogs: DEMO_AUDIT_LOGS,
  };
}

export function saveStoredManufacturingData(data) {
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(data));
  } catch (err) {
    console.warn('Could not save manufacturing data to localStorage:', err);
  }
}

export function resetToDefaultManufacturingData() {
  const initial = {
    organization: DEMO_ORGANIZATION,
    users: DEMO_USERS,
    departments: DEMO_DEPARTMENTS,
    projects: DEMO_PROJECTS,
    clients: DEMO_CLIENTS,
    tasks: DEMO_TASKS,
    notifications: DEMO_NOTIFICATIONS,
    auditLogs: DEMO_AUDIT_LOGS,
  };
  saveStoredManufacturingData(initial);
  return initial;
}
