// ─── Local Storage Store ───────────────────────────────────────────────────────
const STORAGE_KEY = 'etd_demo_store';

function buildDefaultStore() {
  return {
    users: DEMO_USERS,
    departments: DEMO_DEPARTMENTS,
    projects: DEMO_PROJECTS,
    clients: DEMO_CLIENTS,
    tasks: [...DEMO_TASKS],
    notifications: DEMO_NOTIFICATIONS,
    auditLogs: DEMO_AUDIT_LOGS,
  };
}

export function getStoredManufacturingData() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return buildDefaultStore();
    const parsed = JSON.parse(raw);
    // Always re-seed reference arrays to prevent stale data on schema updates
    return {
      ...parsed,
      users: DEMO_USERS,
      departments: DEMO_DEPARTMENTS,
      projects: DEMO_PROJECTS,
      clients: DEMO_CLIENTS,
      notifications: parsed.notifications || DEMO_NOTIFICATIONS,
      auditLogs: parsed.auditLogs || DEMO_AUDIT_LOGS,
    };
  } catch {
    return buildDefaultStore();
  }
}

export function saveStoredManufacturingData(store) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(store));
  } catch {}
}
